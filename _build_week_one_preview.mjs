// Builds the data + stills for the playable Week One preview (quiz result screen and homepage;
// assets/week-one.js renders it):
//   assets/week-one-data.js      the app's real Week 1 per age group (Day 1 exercise by exercise + the week)
//   assets/week-one/<id>.jpg     one still per Day 1 exercise (480 px wide)
// Source of truth: campaigns/week1/weeks.json (made by the app's own program engine, see its README)
// and the stills in campaigns/week1/img. Nothing here is hand-written training content.
// Run from the Website folder (needs ffmpeg on PATH for the stills):  node _build_week_one_preview.mjs
import fs from 'fs';
import path from 'path';
import { execFileSync } from 'child_process';

const SRC = path.resolve('../../campaigns/week1');
const w = JSON.parse(fs.readFileSync(path.join(SRC, 'weeks.json'), 'utf8'));
const X = w.exercises;
const OUT_IMG = 'assets/week-one';
fs.mkdirSync(OUT_IMG, { recursive: true });

const KEYS = { kids: '9_11', youth: '12_14', teen: '15_18', adult: '19_39', masters: '40plus' };
const clean = (s) => String(s || '').replace(/\s+/g, ' ').trim();
// same plain names as the free PDFs (campaigns/week1/build.mjs NAME)
const NAME = { 'Fast Feet / Ladder Equiv': 'Fast Feet', 'Backpack Swing (KB Pattern)': 'Backpack Swing', 'Brisk Walk (Zone 2)': 'Brisk Walk' };
const name = (x) => { const n = clean(x.name).replace(/\s*\(Youth\)/, ''); return NAME[n] || n; };
function dose(e) {
  const r = clean(e.reps).split(' — ')[0].replace(/\s*-\s*1 rep$/, '').replace(/(\d)m\b/, '$1 m');
  if (e.sets > 1) return e.sets + ' × ' + r;
  return /^\d+(-\d+)?$/.test(r) ? r + ' reps' : r;
}
const PHASE = { warmup: 'w', main: 'm', cooldown: 'c' };

const out = {};
const skipped = [];
const stills = new Set();
for (const [g, key] of Object.entries(KEYS)) {
  const grp = w.groups[g];
  const days = grp.week.map((d) => ({ d: d.dayOfWeek.slice(0, 3), t: d.type, n: d.sessionName || '', m: d.minutes || 0 }));
  const d1 = grp.week[0];
  const items = [];
  for (const e of d1.exercises) {
    const x = X[e.id];
    const still = path.join(SRC, 'img', e.id + '.jpg');
    if (!x || !x.video || !fs.existsSync(still)) { skipped.push(key + ':' + e.id); continue; }
    stills.add(e.id);
    items.push({
      id: e.id, n: name(x), r: dose(e), rest: e.restSeconds || 0, p: PHASE[e.phase] || 'm',
      cue: clean((x.cueSentences || [])[0] || ''), v: x.video,
    });
  }
  const wk2 = grp.later && grp.later['2'];
  out[key] = {
    label: grp.label.replace(/^Ages\s+/, ''),
    sessions: days.filter((d) => d.m > 0).length,
    game: (days.find((d) => d.t === 'game') || {}).d || '',
    days,
    day1: { d: d1.dayOfWeek.slice(0, 3), n: d1.sessionName, m: d1.minutes, total: d1.exercises.length, items },
    week2: wk2 ? clean(wk2.weekLabel).replace(/^Week 2\s*[—-]\s*/, '') : '',
  };
}
for (const id of stills) {
  const dst = path.join(OUT_IMG, id + '.jpg');
  execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', path.join(SRC, 'img', id + '.jpg'), '-vf', 'scale=480:-2', '-q:v', '5', dst]);
}
const banner = '/* Generated by _build_week_one_preview.mjs from campaigns/week1/weeks.json. Do not edit by hand. */\n';
fs.writeFileSync('assets/week-one-data.js', banner + 'window.EHD_WEEK1=' + JSON.stringify(out) + ';\n');
for (const [k, v] of Object.entries(out)) console.log(k, '|', v.sessions, 'sessions, game', v.game, '| day 1:', v.day1.n, v.day1.m + ' min,', v.day1.items.length, 'of', v.day1.total, 'on video | week 2:', v.week2);
console.log('skipped (no video or still):', skipped.join(', ') || 'none');
const imgBytes = [...stills].reduce((s, id) => s + fs.statSync(path.join(OUT_IMG, id + '.jpg')).size, 0);
console.log(stills.size, 'stills,', Math.round(imgBytes / stills.size / 1024) + ' KB avg | data', fs.statSync('assets/week-one-data.js').size, 'bytes');
